-- Server push reminders. Private schema, not exposed through the REST API;
-- only the push-reminders edge function (via SUPABASE_DB_URL) touches it.
create extension if not exists pg_cron;
create extension if not exists pg_net;
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table private.push_config (
  id int primary key default 1 check (id = 1),
  subject text not null default 'mailto:studyflow@example.com',
  vapid_public text,   -- generated by the edge function on first use
  vapid_private text,
  cron_secret text not null default encode(extensions.gen_random_bytes(24), 'hex')
);
insert into private.push_config (id) values (1);

create table private.push_subscriptions (
  endpoint text primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  p256dh text not null,
  auth text not null,
  tz text not null default 'Asia/Bangkok',
  created_at timestamptz not null default now()
);
create index on private.push_subscriptions (user_id);

create table private.push_sent (
  user_id uuid not null references auth.users (id) on delete cascade,
  key text not null,
  sent_at timestamptz not null default now(),
  primary key (user_id, key)
);
alter table private.push_config enable row level security;
alter table private.push_subscriptions enable row level security;
alter table private.push_sent enable row level security;

-- Every minute: send any reminders that are due. The secret is read at run time.
select cron.schedule('studyflow-push-reminders', '* * * * *', $job$
  select net.http_post(
    url := 'https://tuubosxebiolhuqsqwoo.supabase.co/functions/v1/push-reminders',
    headers := jsonb_build_object('Content-Type', 'application/json',
      'x-cron-secret', (select cron_secret from private.push_config where id = 1)),
    body := '{"action":"run"}'::jsonb,
    timeout_milliseconds := 20000);
$job$);
